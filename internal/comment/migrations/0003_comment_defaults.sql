-- Third pass: the two things a table needs to stay maintainable by someone who
-- is not holding the application code in their head — a server-side default for
-- the timestamps, and the design decisions written down next to the data.
--
-- 1. created_at / updated_at get a DEFAULT now().
--
--    Nothing in the service relies on it: the use cases set both columns from an
--    injected clock, which is what makes time-dependent tests possible. The
--    default is for every other writer — a repair script, an import, a psql
--    session. Without it those writes fail on NOT NULL, and whoever hits the
--    error fills in a timestamp from their own shell, which is exactly the
--    clock we did not want to trust.
--
--    SET DEFAULT is idempotent, so replaying this file changes nothing.
ALTER TABLE comments
	ALTER COLUMN created_at SET DEFAULT now(),
	ALTER COLUMN updated_at SET DEFAULT now();

-- 2. The reasons behind the shape live in the catalogue, not in a design doc
--    nobody can find. `\d+ comments` now answers "why is the primary key a
--    string?" and "which query does this index serve?" without a search.
COMMENT ON TABLE comments IS
	'Reader comments. One row per comment; replies point at their parent through parent_id (ON DELETE CASCADE).';

COMMENT ON COLUMN comments.id IS
	'Random 128-bit identifier, hex encoded, generated by the service. Used as the primary key because it is also the public identifier: the API exposes it, clients store it, and a comment is never looked up by any other key. A surrogate bigint plus a separate public_id would add a column and a join for no gain at this scale.';
COMMENT ON COLUMN comments.delete_token_hash IS
	'SHA-256 of the credential handed to the author once, at creation. NULL means the author has no credential (imported rows): only the site owner can delete those. The plaintext is never stored.';
COMMENT ON COLUMN comments.status IS
	'Moderation state. Only approved rows are publicly readable.';

-- One index per access path, named after the query it serves.
COMMENT ON INDEX comments_thread_status_idx IS
	'Public thread listing and batch counts: (post_slug, status, created_at DESC, id DESC) serves the filter, the sort and the keyset cursor in one ordered scan.';
COMMENT ON INDEX comments_thread_idx IS
	'Thread listing without a status filter (moderator view, status=all). Not a prefix of comments_thread_status_idx, so it cannot be dropped without turning that query into a sort.';
COMMENT ON INDEX comments_parent_idx IS
	'Replies of one comment. Also what keeps ON DELETE CASCADE proportional to one thread instead of the whole table: PostgreSQL never indexes a foreign key on its own.';
